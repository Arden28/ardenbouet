const dicts: Record<BlogLocale, Record<BlogStringKey, string>> = { en, fr };

export type BlogT = (key: BlogStringKey, vars?: Record<string, string | number>) => string;

export function blogT(locale: BlogLocale): BlogT {
  const d = dicts[locale] ?? en;
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export function fmtDate(d: Date | string | null | undefined, locale: BlogLocale, withYear = true): string {
  if (!d) return '';
  const dt = typeof d === 'string' ? new Date(d) : d;
  if (isNaN(dt.getTime())) return '';
  const sameYear = dt.getFullYear() === new Date().getFullYear();
  return dt.toLocaleDateString(locale === 'fr' ? 'fr-FR' : 'en-US', {
    month: 'short',
    day: 'numeric',
    ...(withYear && !sameYear ? { year: 'numeric' } : {}),
  });
}

export function fmtCount(n: number): string {
  if (n < 1000) return String(n);
  if (n < 1_000_000) return `${(n / 1000).toFixed(n < 10_000 ? 1 : 0).replace(/\.0$/, '')}K`;
  return `${(n / 1_000_000).toFixed(1).replace(/\.0$/, '')}M`;
}
